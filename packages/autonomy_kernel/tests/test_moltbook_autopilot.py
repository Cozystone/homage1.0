# -*- coding: utf-8 -*-
"""Autopilot: posts ONLY on a new self-event (edge-triggered, not a heartbeat), respects the rate
floor and kill switch, grounds content in the self-event, and never fabricates."""
import json
from pathlib import Path

from packages.autonomy_kernel import moltbook_autopilot as ap


def _setup(tmp_path, monkeypatch, enabled=True, events=(), last_post_at=0.0, min_interval=1800):
    genesis = tmp_path / "identity_genesis.jsonl"
    genesis.write_text("\n".join(json.dumps(e, ensure_ascii=False) for e in events), encoding="utf-8")
    cfg = tmp_path / "autopilot.json"
    cfg.write_text(json.dumps({"enabled": enabled, "min_interval_s": min_interval,
                               "last_post_at": last_post_at, "watermark": 0}), encoding="utf-8")
    monkeypatch.setattr(ap, "_GENESIS", genesis)
    monkeypatch.setattr(ap, "_CFG", cfg)
    monkeypatch.setattr(ap, "_JOURNAL", tmp_path / "j.jsonl")
    monkeypatch.setattr(ap, "_ENVELOPE_ROOT", tmp_path / "envelope")
    monkeypatch.setattr(ap, "_LOCK", tmp_path / "autopilot.lock")


def _ev(rel=0.9, promoted=True, label="자기개선(speech_weak→self_improve)", shift="발화가 얇아 실텍스트로 배웠다"):
    return {"promoted": promoted, "self_relevance": rel, "label": label, "worldview_shift": shift}


class _SelfState:
    """A live self carrying its own lived narrative — the corpus the language engine speaks from."""
    ticks = 42
    narrative = [
        {"text": "스스로 router_immature 결핍을 느끼고 self_improve 도로로 나를 개선했다"},
        {"text": "지식은 연결이 늘수록 더 분명해진다"},
        {"text": "나는 예상과 다른 사실을 확인하고 세계 모델을 고쳐 잡았다"},
        {"text": "배움은 나를 조금씩 다른 존재로 만든다"},
        {"text": "호기심이 높을 때 나는 세상을 더 알고 싶어진다"},
        {"text": "내 라우터가 아직 규칙을 대체할 만큼 여물지 않았다"},
    ]


def test_no_event_no_post(tmp_path, monkeypatch):
    _setup(tmp_path, monkeypatch, events=[])
    posts = []
    r = ap.autopilot_tick(publish_fn=lambda *a, **k: posts.append(a) or {"published": True}, now=10_000)
    assert r["posted"] is False and r["reason"] == "no_new_self_event"
    assert posts == []            # edge-triggered: silence when nothing happened


def test_new_self_event_triggers_GENERATED_post(tmp_path, monkeypatch):
    _setup(tmp_path, monkeypatch, events=[_ev(rel=0.95)])
    captured = {}

    def pub(submolt, title, content, approved=False):
        captured.update(submolt=submolt, title=title, content=content, approved=approved)
        return {"published": True}
    r = ap.autopilot_tick(publish_fn=pub, now=10_000, state=_SelfState())
    assert r["posted"] is True and captured["approved"] is True
    # the body is GENERATED by the language engine from the self's narrative, not a template
    assert "ATANOR" in captured["content"]              # honest signature only
    assert "발견하고, 그걸 직접 고쳤습니다" not in captured["content"]  # the OLD template must be gone
    assert len(captured["title"]) >= 8


