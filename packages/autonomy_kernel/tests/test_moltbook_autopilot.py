def test_unavailable_interprocess_lock_blocks_before_state_or_publish(
        tmp_path, monkeypatch):
    _setup(tmp_path, monkeypatch, events=[_ev(rel=0.95)])

    class _UnavailableLock:
        def __enter__(self):
            return False

        def __exit__(self, *_args):
            return False

    monkeypatch.setattr(ap, "_tick_lock", lambda: _UnavailableLock())
    posts = []
    result = ap.autopilot_tick(
        publish_fn=lambda *a, **k: posts.append((a, k)) or {"published": True},
        now=10_000,
        state=_SelfState(),
    )

    assert result == {
        "posted": False,
        "reason": "autopilot_busy_or_lock_unavailable",
    }
    assert posts == []
