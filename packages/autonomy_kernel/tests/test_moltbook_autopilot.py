def test_state_reservation_failure_blocks_before_publish(tmp_path, monkeypatch):
    _setup(tmp_path, monkeypatch, events=[_ev(rel=0.95)])
    real_save = ap._save_cfg
    calls = 0

    def fail_second_save(cfg):
        nonlocal calls
        calls += 1
        if calls == 2:
            return False
        return real_save(cfg)

    monkeypatch.setattr(ap, "_save_cfg", fail_second_save)
    posts = []
    result = ap.autopilot_tick(
        publish_fn=lambda *a, **k: posts.append((a, k)) or {"published": True},
        now=10_000,
        state=_SelfState(),
    )

    assert result == {"posted": False, "reason": "state_persistence_unavailable"}
    assert posts == []


